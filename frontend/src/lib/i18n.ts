export function normalizeLanguage(value: string | null | undefined): Language {
  return value === "zh-CN" ? "zh-CN" : DEFAULT_LANGUAGE;
}

export function translate(
  language: Language,
  key: TranslationKey,
  params: TranslationParams = {},
): string {
  const template = DICTIONARIES[language][key] ?? EN[key] ?? key;
  return template.replace(/{{(\w+)}}/g, (_, name: string) => String(params[name] ?? `{{${name}}}`));
}

export function localizeText(language: Language, text: string): string {
  if (language === "en" || !text) return text;
  if (ZH_TEXT[text]) return ZH_TEXT[text];
  const shortenedSaCandidate = text.match(/^SA candidate is (\d+) nt because the supplied flanking sequence is shorter than (\d+) nt\.$/);
  if (shortenedSaCandidate) return `由于输入的 flank 短于 ${shortenedSaCandidate[2]} nt，SA candidate 长度为 ${shortenedSaCandidate[1]} nt。`;
  const localizedRequirements = text
    .replace(/arRNA 5' side requires (\d+) paired nt; only (\d+) are available/g, "arRNA 5′ 端需要 $1 个配对 nt；当前仅有 $2 个")
    .replace(/arRNA 3' side requires (\d+) paired nt; only (\d+) are available/g, "arRNA 3′ 端需要 $1 个配对 nt；当前仅有 $2 个");
  if (localizedRequirements !== text) return localizedRequirements;
  const position = text.match(/^Position (\d+)$/);
  if (position) return `位置 ${position[1]}`;
  if (text.endsWith(" loaded")) {
    const subject = text.slice(0, -7);
    return `${ZH_TEXT[subject] ?? subject} 已加载`;
  }
  return text;
}
